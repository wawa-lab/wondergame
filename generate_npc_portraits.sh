# NPC 立绘批量生成脚本
# 使用方法: APP_ID="你的appId" bash generate_npc_portraits.sh
# 支持断点续传：已生成的文件自动跳过

APP_ID="${APP_ID:-21904356647821172819}"
SCRIPT="/Users/chenyinuo02/IdeaProjects/wondergame/.catpaw/skills/skills-market/image-generation/scripts/generate_image.py"
OUTDIR="/Users/chenyinuo02/IdeaProjects/wondergame/frontend/public/assets/character/outfits"

TOTAL=12
DONE=0

run_gen() {
  local ref="$1"
  local out="$2"
  local prompt="$3"
  DONE=$((DONE + 1))

  # 断点续传：文件已存在且大于 100KB 则跳过
  if [ -f "$out" ] && [ "$(wc -c < "$out")" -gt 102400 ]; then
    echo "[$DONE/$TOTAL] ⏭️  跳过（已存在）: $(basename $out)"
    return 0
  fi

  echo ""
  echo "[$DONE/$TOTAL] 🎨 生成中: $(basename $out)"
  echo "  参考图: $(basename $ref)"

  python3 "$SCRIPT" \
    --app-id "$APP_ID" \
    --aspect "16:9" \
    --size "1K" \
    --prompt "$prompt" \
    --image "$ref" \
    --out "$out"

  if [ $? -eq 0 ]; then
    echo "[$DONE/$TOTAL] ✅ 完成: $(basename $out)"
  else
    echo "[$DONE/$TOTAL] ❌ 失败: $(basename $out)"
    exit 1
  fi

  # 生成间隔，避免触发限流
  if [ "$DONE" -lt "$TOTAL" ]; then
    echo "  等待 20s..."
    sleep 20
  fi
}

